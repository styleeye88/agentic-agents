"""编码 Agent — 负责代码生成、审查与修复。"""
from typing import Any, Dict, Optional

from .base import BaseAgent


class CoderAgent(BaseAgent):
    def __init__(self, language: str = 'python') -> None:
        super().__init__('coder_agent', system_prompt=f'You are a {language} developer.')
        self.language = language

    def run(self, input_data: dict) -> Dict[str, Any]:
        task: str = input_data.get('task', '')
        code: str = f'# Generated by CoderAgent ({self.language})\n# Task: {task}\ndef solution():\n    pass\n'
        self.update_context('last_task', task)
        return {'status': 'ok', 'code': code, 'language': self.language}

    def review(self, code: str) -> Dict[str, Any]:
        issues: List[str] = []
        if not code.strip():
            issues.append('empty code')
        self.update_context('reviewed_code', code)
        return {'status': 'ok', 'issues': issues, 'count': len(issues)}
